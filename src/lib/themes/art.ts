const leaf = (x: number, y: number, s: number) =>
	`M${x} ${y}c${s * 0.3} ${-s * 0.35} ${s * 0.85} ${-s * 0.2} ${s} ${s * 0.25}c${-s * 0.45} ${s * 0.2} ${-s * 0.85} ${s * 0.05} ${-s} ${-s * 0.25}z M${x} ${y}l${s * 0.8} ${s * 0.12}`;

/** A small flower at x, y */
