// Writes the themes as CSS custom properties: one rule per theme with its light values and
// their *-night counterparts, which the Tailwind tokens in theme.css read. Any element with
// data-accent="<theme>" shows that theme (html for the app, swatches in the picker).
import { DEFAULT_THEME, MEANING, PALETTES, THEME_IDS, type Palette } from './palettes.ts';

const NAMES: Record<keyof Palette, string> = {
	canvas: 'canvas',
	surface: 'surface',
	surfaceMuted: 'surface-muted',
	ink: 'ink',
	inkMuted: 'ink-muted',
	accent: 'accent',
	accentSoft: 'accent-soft',
	heroBg: 'hero-bg',
	heroFg: 'hero-fg'
};

const declarations = (values: Record<string, string>, suffix = '') =>
	Object.entries(values).map(
		([key, value]) => `\t--${NAMES[key as keyof Palette] ?? key}${suffix}: ${value};`
	);

export function themesCss() {
	const rules = THEME_IDS.map((id) => {
		const { light, dark } = PALETTES[id];
		const selector =
			id === DEFAULT_THEME ? `:root,\n[data-accent='${id}']` : `[data-accent='${id}']`;
		return [`${selector} {`, ...declarations(light), ...declarations(dark, '-night'), '}'].join(
			'\n'
		);
	});
	const meaning = [
		':root {',
		...Object.entries(MEANING.light).map(([key, value]) => `\t--${key}: ${value};`),
		...Object.entries(MEANING.dark).map(([key, value]) => `\t--${key}-night: ${value};`),
		'}'
	].join('\n');
	return [
		'/* Generated by `pnpm themes` from src/lib/themes/palettes.ts: edit the palettes there. */',
		...rules,
		meaning,
		''
	].join('\n\n');
}
