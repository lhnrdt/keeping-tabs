// Downloads the pinned datasets and writes src/lib/expense/dataset/keywords.json.
// Run with `pnpm keywords:generate` after changing config.ts.
import { writeFile } from 'node:fs/promises';
import { buildKeywords } from './build.ts';
import { IGNORED, LOCALES, MIN_LETTERS, PLACE_TYPES, REGIONS, SOURCES } from './config.ts';

const OUTPUT = new URL('../../src/lib/expense/dataset/keywords.json', import.meta.url);

const cdn = (source: { name: string; version: string }, path: string) =>
	`https://cdn.jsdelivr.net/npm/${source.name}@${source.version}/${path}`;

// eslint-disable-next-line @typescript-eslint/no-explicit-any -- untyped dataset JSON, checked by buildKeywords
async function fetchJson(url: string): Promise<any> {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url}: ${response.status}`);
	return response.json();
}

const nsi = (await fetchJson(cdn(SOURCES.nsi, 'dist/json/nsi.min.json'))).nsi;
const presetsByLocale = await Promise.all(
	LOCALES.map(async (locale) => {
		const translation = await fetchJson(
			cdn(SOURCES.presets, `dist/translations/${locale}.min.json`)
		);
		return translation[locale]?.presets?.presets ?? {};
	})
);

const keywords = buildKeywords(nsi, presetsByLocale, {
	placeTypes: PLACE_TYPES,
	regions: REGIONS,
	minLetters: MIN_LETTERS,
	ignored: IGNORED
});

const output = {
	note: 'Generated by scripts/category-keywords/generate.ts. Do not edit; change config.ts and regenerate.',
	sources: Object.values(SOURCES),
	keywords
};
await writeFile(OUTPUT, JSON.stringify(output, null, '\t') + '\n');

const count = Object.values(keywords).reduce((sum, list) => sum + list.length, 0);
console.log(`Wrote ${count} keywords to ${OUTPUT.pathname}`);
